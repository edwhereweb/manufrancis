<?php

declare(strict_types=1);

/**
 * Writes app/config.local.php from environment variables (GitHub Actions secrets).
 * Usage: php bin/make-config.php > app/config.local.php
 */

$required = ['APP_KEY', 'ADMIN_USER', 'ADMIN_PASSWORD_HASH', 'DB_NAME', 'DB_USER', 'DB_PASSWORD'];
foreach ($required as $name) {
    if ((string) getenv($name) === '') {
        fwrite(STDERR, "Missing required secret: {$name}\n");
        exit(1);
    }
}
if (strlen((string) getenv('APP_KEY')) < 32) {
    fwrite(STDERR, "APP_KEY must be at least 32 characters\n");
    exit(1);
}
if (!str_starts_with((string) getenv('ADMIN_PASSWORD_HASH'), '$2y$') && !str_starts_with((string) getenv('ADMIN_PASSWORD_HASH'), '$argon2')) {
    fwrite(STDERR, "ADMIN_PASSWORD_HASH must be a hash from bin/hash-password.php, not a plain password\n");
    exit(1);
}

$config = [
    'env'                 => 'production',
    'site_url'            => getenv('SITE_URL') ?: 'https://manufrancis.com',
    'app_key'             => getenv('APP_KEY'),
    'admin_user'          => getenv('ADMIN_USER'),
    'admin_password_hash' => getenv('ADMIN_PASSWORD_HASH'),
    'admin_email'         => getenv('ADMIN_EMAIL') ?: '',
    'db_driver'           => 'mysql',
    'db_host'             => getenv('DB_HOST') ?: 'localhost',
    'db_name'             => getenv('DB_NAME'),
    'db_user'             => getenv('DB_USER'),
    'db_pass'             => getenv('DB_PASSWORD'),
    'notify_email'        => getenv('NOTIFY_EMAIL') ?: '',
    'mail_from'           => getenv('MAIL_FROM') ?: '',
    'privacy_email'       => getenv('PRIVACY_EMAIL') ?: '',
];

echo "<?php\n// Generated by bin/make-config.php during deploy. Do not commit.\nreturn " . var_export($config, true) . ";\n";
